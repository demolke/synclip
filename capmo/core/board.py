"""
ChArUco board model + detection -- the ONE implementation shared by the live UI
(:mod:`capmo.core.board_coverage`), ``extract_keypoints --calib`` and
``calibrate_board``.

* :class:`BoardConfig` -- the board definition (must match the print), also the
  ``board`` block of a session manifest / ``rig.json``.
* :func:`detect` -- one image -> :class:`Detection` (ChArUco corners + ids and
  the raw ArUco marker count).
* :class:`BoardDetector` -- :func:`detect` plus the layout auto-resolve: lots of
  markers but zero interpolated corners means the board model does not match
  the print (legacy vs new ChArUco layout, or -- with ``try_swap`` -- the
  squares given as 5x8 for an 8x5 board); the alternatives are tried and the
  first that yields corners is adopted.
* View-quality metrics used by both the offline calibration report and the live
  coverage indicator: :func:`coverage` (fraction of image grid cells with a
  corner), :func:`rough_tilt` (board tilt vs the image plane from a homography),
  :func:`non_degenerate` (corners span an area, not a single row) and
  :func:`sharpness` (focus / motion-blur measure of the board region).

The thresholds :data:`GOOD_COVERAGE`, :data:`GOOD_MAX_TILT_DEG`,
:data:`GOOD_VIEWS` and :data:`MIN_CORNERS` are the ones ``calibrate_board``
warns about (see ``capmo/tools/README.md``, "Reading the report").
"""

from __future__ import annotations

import dataclasses
import logging
from dataclasses import dataclass

import numpy as np

log = logging.getLogger("capmo.board")

try:
    import cv2
    _ARUCO = hasattr(cv2, "aruco")
except ImportError:  # pragma: no cover
    cv2 = None
    _ARUCO = False

# --- thresholds shared by calibrate_board (report warnings) and the live tracker
COVERAGE_GRID = (8, 6)          # image cells (x, y) for the coverage fraction
GOOD_COVERAGE = 0.5             # coverage fraction: below -> calibrate_board warns
GOOD_MAX_TILT_DEG = 20.0        # max board tilt: below -> focal weakly determined
GOOD_VIEWS = 15                 # usable views per camera for the intrinsics
MIN_CORNERS = 8                 # calibrate_board --min-corners default
MIN_SHARED_VIEWS = 3            # calibrate_board --min-shared: views a camera pair co-sees


@dataclass
class BoardConfig:
    """A ChArUco board definition (must match the printed/displayed target)."""
    squares_x: int = 8
    squares_y: int = 5
    square_len: float = 0.04      # metres (board square side)
    marker_len: float = 0.02      # metres (ArUco marker side)
    dict_name: str = "DICT_6X6_250"
    # OpenCV changed the ChArUco marker layout in 4.6; boards generated by older
    # OpenCV (or many online generators) use the *legacy* layout. A mismatch
    # detects all the markers but interpolates **zero** corners --
    # :class:`BoardDetector` auto-detects and flips this when it sees that.
    legacy: bool = False

    def dictionary(self):
        return cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, self.dict_name))

    def board(self):
        b = cv2.aruco.CharucoBoard(
            (self.squares_x, self.squares_y), self.square_len, self.marker_len,
            self.dictionary())
        try:
            b.setLegacyPattern(self.legacy)
        except AttributeError:        # very old cv2 without the toggle
            pass
        return b

    def detector(self):
        return cv2.aruco.CharucoDetector(self.board())

    def corners3d(self) -> np.ndarray:
        """(N,3) board-frame coordinates (m, z = 0) of every ChArUco corner id."""
        return np.asarray(self.board().getChessboardCorners(), np.float64)

    def to_dict(self) -> dict:
        return {
            "squares_x": self.squares_x, "squares_y": self.squares_y,
            "square_len": self.square_len, "marker_len": self.marker_len,
            "dict_name": self.dict_name, "legacy": self.legacy,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "BoardConfig":
        return cls(**{k: d[k] for k in d if k in cls.__dataclass_fields__})


@dataclass
class Detection:
    """ChArUco corners found in one image."""
    corners: np.ndarray | None   # (N,1,2) float32 sub-pixel corner locations
    ids: np.ndarray | None       # (N,1) int32 charuco corner ids
    n_markers: int = 0           # ArUco markers found (before corner interpolation)

    @property
    def count(self) -> int:
        return 0 if self.ids is None else int(len(self.ids))

    def points(self) -> np.ndarray:
        """(N,2) float64 corner pixels (empty if none)."""
        if self.corners is None:
            return np.zeros((0, 2))
        return np.asarray(self.corners, np.float64).reshape(-1, 2)

    def id_array(self) -> np.ndarray:
        """(N,) int corner ids (empty if none)."""
        if self.ids is None:
            return np.zeros((0,), int)
        return np.asarray(self.ids).reshape(-1).astype(int)


def _gray(image: np.ndarray) -> np.ndarray:
    return cv2.cvtColor(image, cv2.COLOR_BGR2GRAY) if image.ndim == 3 else image


def detect(image: np.ndarray, detector) -> Detection:
    """Detect the ChArUco board in *image* (BGR or grayscale).

    Reports both the ArUco *marker* count and the interpolated ChArUco *corner*
    count: markers≈full but corners≈0 means the board model (size/pattern/dict)
    doesn't match the print; few markers means resolution/focus/dict.
    """
    charuco_corners, charuco_ids, marker_corners, marker_ids = detector.detectBoard(_gray(image))
    n_markers = 0 if marker_ids is None else int(len(marker_ids))
    det = Detection(charuco_corners, charuco_ids, n_markers)
    log.debug("ChArUco detect: %d markers -> %d corners", n_markers, det.count)
    return det


class BoardDetector:
    """:func:`detect` with the board-layout auto-resolve.

    When a frame shows >= 4 markers but no corner, the alternative layouts are
    tried (legacy <-> new; with *try_swap* also ``squares_x``/``squares_y``
    swapped, and both); the first that yields corners becomes :attr:`cfg`
    (:attr:`switched` counts the switches). With *lock* the layout is fixed
    once any frame produced corners (the live UI); without it every such frame
    may switch again (the offline extractor's historical behaviour, which
    only ever tries the legacy flip).
    """

    def __init__(self, cfg: BoardConfig, *, try_swap: bool = False, lock: bool = False,
                 detect_fn=None) -> None:
        self.cfg = cfg
        self.try_swap = try_swap
        self.lock = lock
        self.locked = False
        self.switched = 0
        self._detect = detect_fn or detect
        self._detector = None
        self._alts: dict = {}

    @property
    def detector(self):
        if self._detector is None:
            self._detector = self.cfg.detector()
        return self._detector

    def _alternatives(self) -> list[BoardConfig]:
        base = self.cfg
        out = [dataclasses.replace(base, legacy=not base.legacy)]
        if self.try_swap:
            swap = dict(squares_x=base.squares_y, squares_y=base.squares_x)
            out += [dataclasses.replace(base, **swap),
                    dataclasses.replace(base, legacy=not base.legacy, **swap)]
        return out

    def __call__(self, image: np.ndarray) -> Detection:
        det = self._detect(image, self.detector)
        if self.locked:
            return det
        if det.count > 0:
            self.locked = self.lock
            return det
        if det.n_markers < 4:
            return det
        for alt in self._alternatives():
            key = (alt.squares_x, alt.squares_y, alt.legacy)
            if key not in self._alts:
                self._alts[key] = alt.detector()
            d2 = self._detect(image, self._alts[key])
            if d2.count > 0:
                log.info("board matched as %dx%d legacy=%s (was %dx%d legacy=%s)",
                         alt.squares_x, alt.squares_y, alt.legacy,
                         self.cfg.squares_x, self.cfg.squares_y, self.cfg.legacy)
                self.cfg = alt
                self._detector = self._alts.pop(key)
                self._alts = {}
                self.switched += 1
                self.locked = self.lock
                return d2
        return det


# --------------------------------------------------------------- view quality
def coverage_cells(img_pts: np.ndarray, size, grid=COVERAGE_GRID) -> np.ndarray:
    """(gy, gx) bool occupancy of the image grid cells hit by corner pixels."""
    w, h = size
    gx, gy = grid
    occ = np.zeros((gy, gx), bool)
    p = np.asarray(img_pts, np.float64).reshape(-1, 2)
    if len(p):
        ix = np.clip((p[:, 0] / w * gx).astype(int), 0, gx - 1)
        iy = np.clip((p[:, 1] / h * gy).astype(int), 0, gy - 1)
        occ[iy, ix] = True
    return occ


def coverage(point_sets, size, grid=COVERAGE_GRID) -> float:
    """Fraction of image grid cells containing at least one detected corner,
    over all views (*point_sets*: iterable of (N,2) pixel arrays)."""
    gx, gy = grid
    occ = np.zeros((gy, gx), bool)
    for p in point_sets:
        occ |= coverage_cells(p, size, grid)
    return float(occ.mean())


def non_degenerate(obj: np.ndarray, square_len: float) -> bool:
    """Corners must span a 2D area (not one row/column)."""
    xy = obj[:, :2] - obj[:, :2].mean(0)
    s = np.linalg.svd(xy, compute_uv=False)
    return len(obj) >= 4 and s[-1] / np.sqrt(len(obj)) > 0.25 * square_len


def rough_tilt(obj: np.ndarray, img: np.ndarray, size) -> tuple[float, float]:
    """(tilt angle deg, tilt direction rad) of the board vs the image plane.

    From the board->image homography with a guessed focal (0.9 x the larger
    image side, centred principal point); good to a few degrees, which is all
    view selection and the coverage hints need.
    """
    w, h = size
    f0 = 0.9 * max(w, h)
    K0 = np.array([[f0, 0, w / 2], [0, f0, h / 2], [0, 0, 1.0]])
    H, _ = cv2.findHomography(obj[:, :2], img, 0)
    if H is None:
        return 0.0, 0.0
    Hn = np.linalg.inv(K0) @ H
    r1 = Hn[:, 0] / np.linalg.norm(Hn[:, 0])
    r2 = Hn[:, 1] / np.linalg.norm(Hn[:, 1])
    n = np.cross(r1, r2)
    n /= np.linalg.norm(n)
    return float(np.degrees(np.arccos(min(1.0, abs(n[2]))))), float(np.arctan2(n[1], n[0]))


def sharpness(image: np.ndarray, img_pts: np.ndarray | None = None, pad: float = 0.05) -> float:
    """Edge steepness of the board region (higher = sharper), in [0, ~0.5].

    The steepest brightness change per pixel across the board's edges (99th
    percentile of the directional gradient), taken in the *weakest* of four
    directions (0/45/90/135 deg, so a one-directional motion blur counts) and
    divided by the region's black/white contrast (5-95th percentile), so it
    does not depend on exposure, board size or resolution. An ideal step
    blurred over sigma pixels scores about ``1 / (2.5 * sigma)``: a crisp board
    ~0.28-0.35, sigma 1.5 px or a 5 px motion smear ~0.17-0.2 (synthetic
    renders, 2 grey levels of noise). Region = the corners' bounding box
    (padded by *pad*), the whole image when *img_pts* is None/empty.
    """
    g = _gray(image)
    if img_pts is not None and len(img_pts):
        p = np.asarray(img_pts, np.float64).reshape(-1, 2)
        x0, y0 = p.min(0)
        x1, y1 = p.max(0)
        dx, dy = (x1 - x0) * pad + 2, (y1 - y0) * pad + 2
        H, W = g.shape[:2]
        xa, xb = int(max(0, x0 - dx)), int(min(W, x1 + dx + 1))
        ya, yb = int(max(0, y0 - dy)), int(min(H, y1 + dy + 1))
        if xb - xa >= 8 and yb - ya >= 8:
            g = g[ya:yb, xa:xb]
    g = g.astype(np.float32)
    contrast = float(np.percentile(g, 95) - np.percentile(g, 5))
    if contrast < 1.0:
        return 0.0
    gs = cv2.GaussianBlur(g, (0, 0), 0.7)              # tame pixel noise
    gx = cv2.Sobel(gs, cv2.CV_32F, 1, 0, ksize=3) / 8.0
    gy = cv2.Sobel(gs, cv2.CV_32F, 0, 1, ksize=3) / 8.0
    steep = min(float(np.percentile(np.abs(np.cos(a) * gx + np.sin(a) * gy), 99))
                for a in np.radians([0.0, 45.0, 90.0, 135.0]))
    return steep / contrast
